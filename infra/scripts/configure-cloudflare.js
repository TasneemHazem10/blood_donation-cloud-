'use strict';

/*
 * Public deployment helper: Cloudflare Workers static assets + Neon Postgres.
 *
 * Every credential comes from environment variables. The script never writes a
 * secret into the repository or into the generated frontend bundle. Run it
 * from the project root after `npx wrangler login` has succeeded.
 */
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '../..');
const frontendDir = path.join(root, '.data', 'frontend-deploy');
const services = ['drive', 'donor', 'booking'];
// Optional bootstrap path: a fresh unauthenticated Cloudflare preview account
// has no saved credentials. Wrangler accepts --temporary on both `deploy` and
// `secret put`; the final deployment uses `wrangler login` (CF_TEMPORARY=0).
const temporary = process.env.CF_TEMPORARY === '1';
const deployFlags = temporary ? ['--temporary'] : [];
const workerUrls = {
  drive: process.env.DRIVE_WORKER_URL || '',
  donor: process.env.DONOR_WORKER_URL || '',
  booking: process.env.BOOKING_WORKER_URL || ''
};

function required(name) {
  const value = process.env[name];
  if (!value) {
    console.error(`Missing required environment variable: ${name}`);
    process.exit(1);
  }
  return value;
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd || root,
    env: { ...(options.env || process.env) },
    encoding: 'utf8',
    input: options.input,
    maxBuffer: 10 * 1024 * 1024,
    // wrangler secret put reads from stdin. With stdio[0] === 'ignore' the
    // supplied input is silently discarded, leaving empty secrets.
    stdio: options.quiet
      ? (options.input !== undefined ? ['pipe', 'pipe', 'pipe'] : ['ignore', 'pipe', 'pipe'])
      : ['pipe', 'inherit', 'inherit']
  });
  if (result.error) throw result.error;
  if (result.status !== 0) {
    // Never echo a claim URL or API token into logs or the terminal.
    const safeError = `${result.stderr || ''}`
      .replace(/https:\/\/dash\.cloudflare\.com\/claim-preview\?claimToken=[^\s"']+/g, '<claim URL saved to .data/cloudflare-claim.txt>')
      .replace(/\b(?:CLOUDFLARE_API_TOKEN|apiToken)\s*[:=]\s*[^\s"']+/gi, '$1=<redacted>');
    throw new Error(`${command} ${args.join(' ')} exited with ${result.status}\n${safeError}`);
  }
  // Wrangler prints the deployed URL to stdout but warnings to stderr; both
  // are needed by the URL detector. A fresh temporary account also prints a
  // bearer-like claim URL; save it only in the git-ignored .data folder.
  const output = `${result.stdout || ''}${result.stderr || ''}`;
  const claim = output.match(/https:\/\/dash\.cloudflare\.com\/claim-preview\?claimToken=[^\s"']+/);
  if (claim) {
    fs.mkdirSync(path.join(root, '.data'), { recursive: true });
    const claimFile = path.join(root, '.data', 'cloudflare-claim.txt');
    const value = `${claim[0]}\n`;
    if (!fs.existsSync(claimFile) || fs.readFileSync(claimFile, 'utf8') !== value) {
      fs.writeFileSync(claimFile, value);
      console.log('A new Cloudflare claim link was saved to .data/cloudflare-claim.txt (git-ignored).');
    }
  }
  return output;
}

function npx(args, options) {
  // Launch the locally installed wrangler directly. Spawning npx.cmd through
  // spawnSync fails with EINVAL on Windows, but node <wrangler.js> works in
  // every runtime and keeps the exact same pinned dependency version.
  if (args[0] === 'wrangler') {
    return run(process.execPath, [
      path.join(root, 'node_modules', 'wrangler', 'bin', 'wrangler.js'),
      ...args.slice(1)
    ], options);
  }
  return run(process.platform === 'win32' ? 'npx.cmd' : 'npx', args, options);
}

function putSecret(service, name, value) {
  if (value === undefined || value === null || value === '') return;
  npx([
    'wrangler', 'secret', 'put', name, ...deployFlags,
    '--config', path.join(root, 'services', service, 'wrangler.toml')
  ], { input: `${value}\n`, quiet: true });
  console.log(`  set ${service} secret: ${name}`);
}

async function applySchema(databaseUrl) {
  const { neon } = require(path.join(root, 'node_modules', '@neondatabase', 'serverless'));
  const sql = neon(databaseUrl);
  const schema = fs.readFileSync(path.join(root, 'infra', 'db', 'schema.sql'), 'utf8');
  for (const statement of schema.split(';').map((text) => text.trim()).filter(Boolean)) {
    await sql.query(statement);
  }
  console.log('Neon schema applied (9 tables).');
}

// Build a disposable copy of the static site so the tracked frontend/js/config.js
// keeps its localhost defaults and `git status` stays clean after a deploy.
function prepareFrontend(frontendUrl, siteKey) {
  fs.rmSync(frontendDir, { recursive: true, force: true });
  fs.cpSync(path.join(root, 'frontend'), frontendDir, { recursive: true });
  const contents = `// Generated by infra/scripts/configure-cloudflare.js. No secrets in this file.
window.BDO = {
  services: {
    drive: ${JSON.stringify(workerUrls.drive)},
    donor: ${JSON.stringify(workerUrls.donor)},
    booking: ${JSON.stringify(workerUrls.booking)}
  },
  turnstileSiteKey: ${JSON.stringify(siteKey || '')},
  localWebsite: ${JSON.stringify(frontendUrl || '')},
  appName: 'BloodLink'
};
`;
  fs.writeFileSync(path.join(frontendDir, 'js', 'config.js'), contents);
  fs.writeFileSync(path.join(frontendDir, 'wrangler.toml'), [
    'name = "bdo-organizer"',
    'compatibility_date = "2026-01-01"',
    'assets = { directory = "./", html_handling = "auto-trailing-slash", not_found_handling = "single-page-application" }',
    ''
  ].join('\n'));
  return frontendDir;
}

function findDeployedUrl(output) {
  const found = output.match(/https:\/\/[A-Za-z0-9.-]+\.(?:pages|workers)\.dev/);
  return found ? found[0] : '';
}

// Service bindings cannot be created until the target Worker exists, and an
// unclaimed preview account may allow 0 cron triggers. The permanent account
// keeps the declared trigger; this bootstrap path is only for a fresh account.
function generatedWorkerConfig(service, { stripBindings = false } = {}) {
  const directory = path.join(root, '.data', 'workers-bootstrap');
  fs.mkdirSync(directory, { recursive: true });
  const source = fs.readFileSync(path.join(root, 'services', service, 'wrangler.toml'), 'utf8');
  const mainPath = path.join(root, 'services', service, 'dist', 'worker.js');
  const lines = [];
  let skipping = false;
  for (const line of source.split(/\r?\n/)) {
    const trimmed = line.trim();
    if ((stripBindings && trimmed === '[[services]]') || trimmed === '[triggers]') {
      skipping = true;
      continue;
    }
    if (skipping) {
      if (/^\[[^\]]+\]/.test(trimmed)) skipping = false;
      else if (stripBindings && /^(binding|service)\s*=/.test(trimmed)) continue;
      else if (!trimmed) { skipping = false; lines.push(''); continue; }
      else skipping = false;
    }
    lines.push(/^main\s*=/.test(trimmed) ? `main = ${JSON.stringify(mainPath)}` : line);
  }
  const suffix = stripBindings ? 'bootstrap' : 'final';
  const configPath = path.join(directory, `${service}-${suffix}.toml`);
  fs.writeFileSync(configPath, lines.join('\n').replace(/\n{3,}/g, '\n\n'));
  return configPath;
}

function bootstrapConfig(service) {
  return generatedWorkerConfig(service, { stripBindings: true });
}

function finalWorkerConfig(service) {
  if (!temporary) return path.join(root, 'services', service, 'wrangler.toml');
  return generatedWorkerConfig(service);
}

async function verify() {
  const checks = [
    ['drive', `${workerUrls.drive.replace(/\/$/, '')}/api/health/drive`],
    ['donor', `${workerUrls.donor.replace(/\/$/, '')}/api/health/donor`],
    ['booking', `${workerUrls.booking.replace(/\/$/, '')}/api/health/booking`]
  ];
  let failed = 0;
  for (const [name, url] of checks) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(15000) });
      console.log(`${response.ok ? 'PASS' : 'FAIL'}  ${name} health (${response.status})`);
      if (!response.ok) failed += 1;
    } catch (error) {
      console.log(`FAIL  ${name} health (${error.message})`);
      failed += 1;
    }
  }
  return failed;
}

(async () => {
  const databaseUrl = required('DATABASE_URL');
  const jwtSecret = required('JWT_SECRET');
  const internalKey = required('INTERNAL_KEY');
  const organizerInvite = required('ORGANIZER_INVITE');
  for (const service of services) workerUrls[service] = required(`${service.toUpperCase()}_WORKER_URL`);

  let frontendUrl = process.env.FRONTEND_URL || '';
  const secretEntries = () => Object.entries({
    DATABASE_URL: databaseUrl,
    JWT_SECRET: jwtSecret,
    INTERNAL_KEY: internalKey,
    ORGANIZER_INVITE: organizerInvite,
    DRIVE_SERVICE_URL: workerUrls.drive,
    DONOR_SERVICE_URL: workerUrls.donor,
    BOOKING_SERVICE_URL: workerUrls.booking,
    TURNSTILE_SECRET: process.env.TURNSTILE_SECRET || '',
    BREVO_API_KEY: process.env.BREVO_API_KEY || '',
    RESEND_API_KEY: process.env.RESEND_API_KEY || '',
    EMAIL_FROM: process.env.EMAIL_FROM || '',
    EMAIL_MODE: (process.env.RESEND_API_KEY || process.env.BREVO_API_KEY) ? 'live' : 'log',
    CORS_ORIGINS: frontendUrl
  }).filter(([, value]) => value);

  function workerDeployOptions() {
    return { quiet: true };
  }

  function deployWorkers() {
    for (const service of services) {
      npx([
        'wrangler', 'deploy', ...deployFlags,
        '--config', finalWorkerConfig(service)
      ], workerDeployOptions());
    }
  }

  function bootstrapWorkers() {
    return services.map((service) => npx([
      'wrangler', 'deploy', ...deployFlags, '--config', bootstrapConfig(service)
    ], workerDeployOptions()));
  }

  function setWorkerSecrets() {
    for (const service of services) {
      for (const [name, value] of secretEntries()) putSecret(service, name, value);
    }
  }

  console.log('==> Bundling Cloudflare Workers');
  run(process.execPath, ['infra/scripts/bundle-workers.js']);

  console.log('==> Applying Neon schema');
  await applySchema(databaseUrl);

  console.log('==> Initial Worker deployment');
  const bootstrapOutputs = bootstrapWorkers();
  services.forEach((service, index) => {
    const detected = findDeployedUrl(bootstrapOutputs[index]);
    if (detected) workerUrls[service] = detected;
    console.log(`  ${service}: ${workerUrls[service]}`);
  });

  console.log('==> Setting Worker secrets');
  setWorkerSecrets();

  console.log('==> Deploying static site to Cloudflare Workers assets');
  prepareFrontend(frontendUrl, process.env.TURNSTILE_SITE_KEY);
  let deployOutput = npx([
    'wrangler', 'deploy', ...deployFlags, '--config', path.join(frontendDir, 'wrangler.toml')
  ], { quiet: true });
  if (!frontendUrl) frontendUrl = findDeployedUrl(deployOutput);

  if (frontendUrl) {
    console.log(`==> Allowing CORS from ${frontendUrl}`);
    setWorkerSecrets();
    // Redeploy once more with the final site URL embedded in js/config.js.
    prepareFrontend(frontendUrl, process.env.TURNSTILE_SITE_KEY);
    deployOutput = npx([
      'wrangler', 'deploy', ...deployFlags, '--config', path.join(frontendDir, 'wrangler.toml')
    ], { quiet: true });
  } else {
    console.warn('Could not detect the site URL. Set FRONTEND_URL and re-run to fix CORS/config.');
  }

  console.log('==> Redeploying Workers with secrets');
  deployWorkers();

  fs.mkdirSync(path.join(root, '.data'), { recursive: true });
  fs.writeFileSync(path.join(root, '.data', 'cloudflare-urls.json'), JSON.stringify({
    frontend: frontendUrl || null,
    services: workerUrls,
    deployedAt: new Date().toISOString()
  }, null, 2));
  console.log('URLs saved to .data/cloudflare-urls.json (not secret).');

  const failed = await verify();
  if (failed) {
    console.error(`${failed} health check(s) failed. Check Worker logs with: npx wrangler tail <name>`);
    process.exit(1);
  }
  console.log('CLOUDFLARE DEPLOYMENT VERIFIED');
})().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
