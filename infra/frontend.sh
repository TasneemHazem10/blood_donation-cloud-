#!/usr/bin/env bash
# Publishes the single-page website to S3 and points it at the deployed API.
source "$(dirname "$0")/config.sh"
load_state
# The AWS CLI treats spaces in local paths as part of the argument unless they
# are relative to the current directory.
cd "$ROOT" || exit 1

aws_f s3 mb "s3://bdo-web" >/dev/null 2>&1 || true
aws_f s3 cp "frontend/index.html" "s3://bdo-web/index.html" --content-type "text/html; charset=utf-8" >/dev/null
aws_f s3 cp "frontend/css" "s3://bdo-web/css" --recursive --content-type "text/css; charset=utf-8" >/dev/null
aws_f s3 cp "frontend/js" "s3://bdo-web/js" --recursive --content-type "text/javascript; charset=utf-8" >/dev/null

TMP_CONFIG=".data/deploy-config.js"
mkdir -p "$(dirname "$TMP_CONFIG")"
cat > "$TMP_CONFIG" <<EOF
// Generated by infra/frontend.sh. No secrets in this file.
window.BDO = {
  services: {
    drive: "$API_URL",
    donor: "$API_URL",
    booking: "$API_URL"
  },
  turnstileSiteKey: "${TURNSTILE_SITE_KEY:-}",
  appName: "BloodLink"
};
EOF
aws_f s3 cp "$TMP_CONFIG" "s3://bdo-web/js/config.js" --content-type "text/javascript; charset=utf-8" >/dev/null

aws_f s3api put-bucket-policy --bucket bdo-web --policy "{\"Version\":\"2012-10-17\",\"Statement\":[{\"Effect\":\"Allow\",\"Principal\":\"*\",\"Action\":\"s3:GetObject\",\"Resource\":\"arn:aws:s3:::bdo-web/*\"}]}" >/dev/null 2>&1 || true
aws_f s3api put-bucket-website --bucket bdo-web \
  --website-configuration '{"IndexDocument":{"Suffix":"index.html"},"ErrorDocument":{"Key":"index.html"}}' >/dev/null 2>&1 || true

echo "Website deployed: $FLOCI_URL/bdo-web/index.html"
echo "API:              $API_URL"
